create table if not exists campus_event (
 id bigint generated by default as identity primary key,
 owner_id bigint not null references app_users(id),
 title varchar(160) not null, description varchar(4000) not null, category varchar(80) not null,
 starts_at timestamp with time zone not null, ends_at timestamp with time zone not null,
 location varchar(200) not null, latitude double precision, longitude double precision,
 capacity integer check (capacity > 0), status varchar(12) not null default 'DRAFT' check (status in ('DRAFT','PUBLISHED','CANCELLED')),
 hidden boolean not null default false, created_at timestamp with time zone not null default current_timestamp,
 updated_at timestamp with time zone not null default current_timestamp, check (ends_at > starts_at)
);
create index if not exists ix_event_discovery on campus_event(status,hidden,starts_at);
create table if not exists event_registration (
 id bigint generated by default as identity primary key, event_id bigint not null references campus_event(id),
 user_id bigint not null references app_users(id), status varchar(12) not null check (status in ('ACTIVE','CANCELLED')),
 registered_at timestamp with time zone not null default current_timestamp, cancelled_at timestamp with time zone,
 unique(event_id,user_id)
);
create index if not exists ix_registration_member on event_registration(user_id,status);
create table if not exists lost_found_report (
 id bigint generated by default as identity primary key, owner_id bigint not null references app_users(id),
 type varchar(8) not null check (type in ('LOST','FOUND')), title varchar(160) not null, description varchar(4000) not null,
 category varchar(80) not null, incident_at timestamp with time zone not null, location varchar(200) not null,
 latitude double precision, longitude double precision, status varchar(12) not null default 'OPEN' check (status in ('OPEN','RESOLVED','CLOSED')),
 hidden boolean not null default false, created_at timestamp with time zone not null default current_timestamp,
 updated_at timestamp with time zone not null default current_timestamp
);
create index if not exists ix_report_discovery on lost_found_report(hidden,type,status,incident_at);
create table if not exists report_image (
 id bigint generated by default as identity primary key, report_id bigint not null references lost_found_report(id),
 public_id varchar(200) not null unique, secure_url varchar(1024) not null, uploaded_at timestamp with time zone not null default current_timestamp
);
create index if not exists ix_report_image on report_image(report_id);
create table if not exists image_cleanup (
 public_id varchar(200) primary key, retry_after timestamp with time zone not null
);
create table if not exists moderation_history (
 id bigint generated by default as identity primary key, admin_id bigint not null references app_users(id),
 event_id bigint references campus_event(id), report_id bigint references lost_found_report(id),
 action varchar(16) not null, reviewed_at timestamp with time zone not null default current_timestamp,
 check ((event_id is null) <> (report_id is null))
);
